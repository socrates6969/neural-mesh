"""k1 summary: combines results/k1_{held,confirm}_{A,B}.json into results/k1_combined.md (tables + claims).
Usage: python py/k1_summary.py > results/k1_combined.md
EQ / gain claims need BOTH stages (held 31-60 and confirm 61-90) with Holm-adjusted tests computed by the Rust bin (frozen-arm family)."""
import json, os, sys
import numpy as np

RES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results")
FROZEN_ORDER = ["exact", "cosfirst0.98", "cosnew0.75", "supdel", "supsoft8.0", "rec1.0", "exact+supdel", "tier-f16", "tier-int8", "tier.2/.3", "tier.1/.2",
                "exact+supdel+tier.2/.3", "exact+supdel+cosfirst0.95", "summary", "supdel+summary", "fifo50", "fifo25", "lru50", "lru25", "val50", "val25",
                "supdel+fifo25", "supdel+val25"]



def tcrit(df):
    try:
        from scipy import stats
        return float(stats.t.ppf(0.975, df))
    except Exception:
        return 1.96 + 2.4 / max(df, 1)


def pdiff(a, b):
    a = np.array(a, dtype=float); b = np.array(b, dtype=float)
    ok = np.isfinite(a) & np.isfinite(b)
    d = (a - b)[ok]
    n = len(d)
    if n < 3:
        return float("nan"), float("nan"), float("nan"), n
    se = d.std(ddof=1) / np.sqrt(n)
    t = tcrit(n - 1)
    return float(d.mean()), float(d.mean() - t * se), float(d.mean() + t * se), n


def fmt(x):
    return "%+.4f [%+.4f,%+.4f]" % x[:3]



