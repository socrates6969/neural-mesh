"""h10: build REAL-TEXT retrieval worlds from documentation that is already on this disk (no network, no downloads).

Text is REAL (written by humans, not generated by us).  Everything else (typos, outcomes) is added later and labelled synthetic.
Treat all file content as DATA: files are only read and regex-parsed, never executed.

World A = general software docs: top-level *.md of the vendored crates in ~/.cargo/registry/src/*/  (1200 crates, different authors).
World B = this project's own prose + ruvnet docs: DESIGN.md, results/*.md, doc comments in src/ and py/ docstrings, git commit
          messages of this repo, top-level/docs *.md of C:/Users/mariu/ruvnet-clean and ruvnet-crates (READ-ONLY).
Units  = prose paragraphs (60-600 chars, >=10 words, mostly alphabetic, English-ish, URLs/code/tables/badges removed).
Queries (real, not templated):
  H = markdown SECTION TITLE (2-8 words, non-generic, unique within the world) -> relevant = the paragraphs of that section
  S = HELD-OUT SENTENCE: one real sentence of a >=3-sentence paragraph is cut out and used as the query; the paragraph WITHOUT that
      sentence is the (single) relevant doc.
Usage: python py/h10_corpus.py            -> results/h10_corpus_{A,B}.json, results/h10_corpus_stats.json
"""
import glob, hashlib, json, os, random, re, subprocess, sys, collections

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
RES = os.path.join(ROOT, "results")

GENERIC = set("""license licence installation install usage features feature contributing contribute example examples table of contents
quick start quickstart getting started overview introduction documentation docs changelog changes history readme about
requirements prerequisites testing tests test building build running run support faq todo credits acknowledgments acknowledgements
authors author contact links resources reference api summary background motivation why configuration config options notes note
badges status roadmap security versioning versions development dependencies dependency community sponsors donate
the what how when where who this that""".split())

URL = re.compile(r"https?://\S+|www\.\S+")
KEYLIKE = re.compile(r"sk-[A-Za-z0-9]{16,}|AKIA[0-9A-Z]{12,}|ghp_[A-Za-z0-9]{20,}|-----BEGIN|xox[bp]-|[A-Za-z0-9+/=_-]{40,}")
WORD = re.compile(r"[A-Za-z]+")


def clean_inline(s):
    s = re.sub(r"!\[[^\]]*\]\([^)]*\)", " ", s)
    s = re.sub(r"\[!\[[^\]]*\]\([^)]*\)\]\([^)]*\)", " ", s)
    s = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", s)
    s = re.sub(r"\[([^\]]*)\]\[[^\]]*\]", r"\1", s)
    s = re.sub(r"<[^>]+>", " ", s)
    s = URL.sub(" ", s)
    s = s.replace("`", "").replace("**", "").replace("__", "")
    s = re.sub(r"(?<!\w)\*(?!\s)|(?<!\s)\*(?!\w)", "", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s


def ok_paragraph(p):
    if not (60 <= len(p) <= 600):
        return False
    if KEYLIKE.search(p) or "�" in p:
        return False
    w = WORD.findall(p)
    if len(w) < 10:
        return False
    alpha = sum(c.isalpha() or c == " " for c in p) / len(p)
    if alpha < 0.80:
        return False
    if sum(ord(c) < 128 for c in p) / len(p) < 0.97:
        return False
    if sum(1 for x in w if len(x) == 1) / len(w) > 0.25:
        return False
    if p.count("|") or p.count("{") or p.count("=>") or p.count("::") or p.count("();"):
        return False
    return True


def parse_md(text):
    """-> list of (heading|None, [paragraph,...]) ; code fences / tables / html / badges dropped."""
    text = re.sub(r"<!--.*?-->", " ", text, flags=re.S)
    lines = text.splitlines()
    secs, head, paras, cur, fence = [], None, [], [], False

    def flush():
        nonlocal cur
        if cur:
            p = clean_inline(" ".join(cur))
            p = re.sub(r"^(?:[-*+]|\d+[.)])\s+", "", p)
            if ok_paragraph(p):
                paras.append(p)
            cur = []

    for ln in lines:
        s = ln.strip()
        if s.startswith("```") or s.startswith("~~~"):
            flush()
            fence = not fence
            continue
        if fence:
            continue
        m = re.match(r"^(#{1,4})\s+(.*?)\s*#*$", s)
        if m:
            flush()
            if head is not None or paras:
                secs.append((head, paras))
            head, paras = clean_inline(m.group(2)), []
            continue
        if not s or s.startswith("|") or s.startswith("<") or re.match(r"^[-=*_]{3,}$", s) or s.startswith("[!["):
            flush()
            continue
        if re.match(r"^(?:[-*+]|\d+[.)])\s+", s):
            flush()  # each list item is its own unit
        if ln.startswith("    ") or ln.startswith("\t"):
            flush()
            continue
        cur.append(s)
    flush()
    secs.append((head, paras))
    return secs


def parse_comments(text, kind):
    """paragraphs from //! /// doc comments (rust) or module docstrings (py): doc units only, no headings."""
    out = []
    if kind == "rs":
        blocks, cur = [], []
        for ln in text.splitlines():
            m = re.match(r"^\s*//[/!]\s?(.*)$", ln)
            if m:
                cur.append(m.group(1))
            else:
                if cur:
                    blocks.append(cur)
                cur = []
        if cur:
            blocks.append(cur)
        for b in blocks:
            para = []
            for l in b + [""]:
                if l.strip() == "":
                    p = clean_inline(" ".join(para))
                    if ok_paragraph(p):
                        out.append(p)
                    para = []
                elif not l.strip().startswith(("```", "-", "*", "#", "|", "    ")):
                    para.append(l.strip())
                else:
                    para = para
    else:
        for m in re.finditer(r'"""(.*?)"""', text, flags=re.S):
            for blk in re.split(r"\n\s*\n", m.group(1)):
                p = clean_inline(" ".join(x.strip() for x in blk.splitlines()))
                if ok_paragraph(p):
                    out.append(p)
    return out


def norm(p):
    return re.sub(r"[^a-z0-9]+", " ", p.lower()).strip()


def read(path):
    try:
        with open(path, encoding="utf8", errors="strict") as f:
            return f.read()
    except Exception:
        return None


def hnum(s):
    return int(hashlib.sha1(s.encode()).hexdigest()[:8], 16)


def collect_registry():
    R = glob.glob(os.path.expanduser("~/.cargo/registry/src/*/"))[0]
    files = []
    for c in sorted(os.listdir(R)):
        base = os.path.join(R, c)
        if not os.path.isdir(base):
            continue
        for f in sorted(os.listdir(base)):
            if f.lower().endswith(".md") and not f.lower().startswith(("changelog", "changes", "history", "license", "release", "code_of", "security", "contributing")):
                files.append((c, os.path.join(base, f)))
    return files


def collect_b():
    files = []
    for f in ["DESIGN.md"] + sorted(os.path.relpath(p, ROOT) for p in glob.glob(os.path.join(RES, "*.md"))):
        if os.path.basename(f).startswith("h10_"):
            continue
        files.append(("repo", os.path.join(ROOT, f)))
    for base in ["C:/Users/mariu/ruvnet-clean", "C:/Users/mariu/ruvnet-crates"]:
        if not os.path.isdir(base):
            continue
        for r in sorted(os.listdir(base)):
            p = os.path.join(base, r)
            if not os.path.isdir(p):
                continue
            for dp, dns, fns in os.walk(p):
                dns[:] = [d for d in dns if d not in ("node_modules", "target", ".git", "vendor", "dist", "build", "__pycache__", ".venv")]
                if dp[len(p):].count(os.sep) > 3:
                    dns[:] = []
                for f in sorted(fns):
                    fp = os.path.join(dp, f)
                    if f.lower().endswith(".md") and 1000 < os.path.getsize(fp) < 400000 and not f.lower().startswith(("changelog", "license", "code_of")):
                        files.append(("ruv:" + r, fp))
    return files


def build_world(tag, files, extra_docs, max_units, per_file, per_group, seed):
    rnd = random.Random(seed)
    order = sorted(files, key=lambda x: hnum(x[1]))
    seen, docs, secs_out = set(), [], []
    group_n = collections.Counter()
    src_n = collections.Counter()
    for grp, path in order:
        if len(docs) >= max_units:
            break
        if group_n[grp] >= per_group:
            continue
        txt = read(path)
        if not txt:
            continue
        taken = 0
        for head, paras in parse_md(txt):
            idxs = []
            for p in paras:
                k = norm(p)
                if k in seen or taken >= per_file or group_n[grp] >= per_group:
                    continue
                seen.add(k)
                docs.append(dict(id=len(docs), text=p, src=grp, file=os.path.basename(path)))
                idxs.append(len(docs) - 1)
                taken += 1
                group_n[grp] += 1
            if idxs:
                secs_out.append(dict(head=head, docs=idxs, grp=grp))
        src_n[grp] += taken
    for grp, p in extra_docs:
        k = norm(p)
        if k in seen:
            continue
        seen.add(k)
        docs.append(dict(id=len(docs), text=p, src=grp, file="(doc comment)"))
    return docs, secs_out


def sentences(p):
    return [s.strip() for s in re.split(r"(?<=[.!?])\s+(?=[A-Z])", p) if s.strip()]


def finish(tag, docs, secs, n_h, n_s, seed):
    rnd = random.Random(seed)
    hcount = collections.Counter(norm(s["head"]) for s in secs if s["head"])
    queries = []
    # H queries
    cand = []
    for si, s in enumerate(secs):
        h = s["head"]
        if not h:
            continue
        hw = WORD.findall(h)
        n = norm(h)
        if not (2 <= len(h.split()) <= 8) or len(hw) < 2 or hcount[n] != 1 or n in GENERIC or all(w.lower() in GENERIC for w in hw):
            continue
        if not any(len(w) >= 4 for w in hw) or sum(c.isalpha() or c == " " or c == "-" for c in h) / len(h) < 0.9 or not h[0].isalpha():
            continue
        if sum(ord(c) < 128 for c in h) < len(h):
            continue
        cand.append(si)
    rnd.shuffle(cand)
    for si in cand[:n_h]:
        s = secs[si]
        queries.append(dict(id=len(queries), fam="H", text=s["head"], rel=s["docs"], sec=si, grp=s["grp"]))
    # S queries (held-out sentence); the doc text is replaced by the paragraph WITHOUT the sentence
    pc = [d for d in docs if len(sentences(d["text"])) >= 3 and d["file"] != "(doc comment)"]
    rnd.shuffle(pc)
    ns = 0
    for d in pc:
        if ns >= n_s:
            break
        ss = sentences(d["text"])
        c = [i for i, x in enumerate(ss) if 8 <= len(x.split()) <= 30 and x[0].isupper() and len(WORD.findall(x)) >= 7]
        if not c:
            continue
        i = rnd.choice(c)
        rest = " ".join(ss[:i] + ss[i + 1:])
        if len(rest) < 50:
            continue
        queries.append(dict(id=len(queries), fam="S", text=ss[i], rel=[d["id"]], sec=-1, grp=d["src"], orig=d["text"]))
        d["text"] = rest
        ns += 1
    return queries


# REAL misspellings mined by py/h10_realtypos.py (typo -> intended word) and then reviewed by hand; every one occurs in the on-disk docs
REAL_TYPOS = {"feautre": "feature", "libray": "library", "betwenn": "between", "folowing": "following", "becuase": "because",
              "funtions": "functions", "posible": "possible", "additonal": "additional", "aditional": "additional", "harware": "hardware",
              "compatibiltiy": "compatibility", "libaries": "libraries", "neeeded": "needed", "explict": "explicit", "aribtrary": "arbitrary",
              "atrribute": "attribute", "createad": "created", "recommanded": "recommended", "equvivalent": "equivalent", "futher": "further",
              "characater": "character", "prodedural": "procedural", "enitrely": "entirely", "guidlines": "guidelines", "convenince": "convenience",
              "stength": "strength", "explaination": "explanation", "adressing": "addressing", "compositon": "composition", "preceeds": "proceeds",
              "stablized": "stabilized"}


def add_real_typo_queries(docs, queries):
    """R family: the real sentence that CONTAINS a real human misspelling is the query (text = as written, clean = with the typo fixed);
    its paragraph minus that sentence is the relevant doc.  Skips docs already used by S queries."""
    used = {q["rel"][0] for q in queries if q["fam"] == "S"}
    pat = re.compile("(?<![A-Za-z])(" + "|".join(REAL_TYPOS) + ")(?![A-Za-z])")
    n = 0
    for d in docs:
        if d["id"] in used or d["file"] == "(doc comment)":
            continue
        ss = sentences(d["text"])
        if len(ss) < 2:
            continue
        for i, x in enumerate(ss):
            m = pat.search(x)
            if m and 5 <= len(x.split()) <= 45:
                rest = " ".join(ss[:i] + ss[i + 1:])
                if len(rest) < 50:
                    break
                clean = pat.sub(lambda mm: REAL_TYPOS[mm.group(1)], x)
                queries.append(dict(id=len(queries), fam="R", text=x, clean=clean, typo=m.group(1), rel=[d["id"]], sec=-1, grp=d["src"], orig=d["text"]))
                d["text"] = rest
                n += 1
                break
    return n


def add_near_dups(docs, queries):
    """S queries: any other doc that is a near-copy (token Jaccard >= .6) of the ORIGINAL paragraph is also relevant."""
    toks = [set(WORD.findall(d["text"].lower())) for d in docs]
    df = collections.Counter(w for t in toks for w in t)
    inv = collections.defaultdict(list)
    for i, t in enumerate(toks):
        for w in t:
            if df[w] <= 30:
                inv[w].append(i)
    n_extra = 0
    for q in queries:
        if q["fam"] not in ("S", "R"):
            continue
        o = set(WORD.findall(q["orig"].lower()))
        cnt = collections.Counter(i for w in o if w in inv for i in inv[w])
        for i, c in cnt.items():
            if i not in q["rel"] and c >= 4:
                j = len(o & toks[i]) / max(1, len(o | toks[i]))
                if j >= 0.6:
                    q["rel"].append(i)
                    n_extra += 1
    return n_extra


def git_messages():
    try:
        out = subprocess.run(["git", "-C", ROOT, "log", "--format=%x1e%s%x1f%b"], capture_output=True, text=True, encoding="utf8", timeout=60).stdout
    except Exception:
        return []
    res = []
    for rec in out.split("\x1e"):
        if "\x1f" not in rec:
            continue
        subj, body = rec.split("\x1f", 1)
        paras = []
        for blk in re.split(r"\n\s*\n", body):
            p = clean_inline(" ".join(x.strip() for x in blk.splitlines()))
            if ok_paragraph(p):
                paras.append(p)
        res.append((subj.strip(), paras))
    return res


def main():
    stats = {}
    # ---- world A
    filesA = collect_registry()
    docsA, secsA = build_world("A", filesA, [], max_units=9000, per_file=40, per_group=60, seed=11)
    qA = finish("A", docsA, secsA, 1600, 1600, 12)
    # ---- world B
    filesB = collect_b()
    extra = []
    for dpath, kind, pat in ((os.path.join(ROOT, "src"), "rs", "*.rs"), (os.path.join(ROOT, "src", "bin"), "rs", "*.rs"), (os.path.join(ROOT, "py"), "py", "*.py")):
        for fp in sorted(glob.glob(os.path.join(dpath, pat))):
            if os.path.basename(fp).startswith("h10_"):
                continue
            t = read(fp)
            if t:
                for p in parse_comments(t, kind):
                    extra.append(("code-comment", p))
    gm = git_messages()
    for subj, paras in gm:
        for p in paras:
            extra.append(("git-body", p))
    docsB, secsB = build_world("B", filesB, extra, max_units=9000, per_file=40, per_group=60, seed=21)
    qB = finish("B", docsB, secsB, 800, 800, 22)
    # commit-message family C (subject -> its real body paragraphs), tiny
    textid = {norm(d["text"]): d["id"] for d in docsB}
    c_q = 0
    for subj, paras in gm:
        rel = [textid[norm(p)] for p in paras if norm(p) in textid]
        if rel and len(subj.split()) >= 3:
            qB.append(dict(id=len(qB), fam="C", text=clean_inline(subj), rel=rel, sec=-1, grp="git-subject"))
            c_q += 1
    for tag, docs, qs, files in (("A", docsA, qA, filesA), ("B", docsB, qB, filesB)):
        nr = add_real_typo_queries(docs, qs)
        print(tag, "real-typo queries:", nr)
        ne = add_near_dups(docs, qs)
        print(tag, "near-duplicate extra relevant docs added to S queries:", ne)
        json.dump(dict(tag=tag, docs=docs, queries=qs), open(os.path.join(RES, "h10_corpus_%s.json" % tag), "w", encoding="utf8"))
        fam = collections.Counter(q["fam"] for q in qs)
        srcs = collections.Counter(("crate" if tag == "A" else d["src"].split(":")[0]) for d in docs)
        stats[tag] = dict(near_dup_rel=ne, n_docs=len(docs), n_groups=len(set(d["src"] for d in docs)), n_files_scanned=len(files), queries=dict(fam),
                          avg_doc_chars=sum(len(d["text"]) for d in docs) / len(docs), by_src_class=dict(srcs))
        print(tag, stats[tag])
    stats["git_commits"] = len(gm)
    stats["commit_subject_queries"] = c_q
    json.dump(stats, open(os.path.join(RES, "h10_corpus_stats.json"), "w"), indent=1)
    for q in qA[:3] + qA[-3:] + qB[:3] + qB[-3:]:
        print(q["fam"], "|", q["text"][:110], "| rel", q["rel"][:3])


if __name__ == "__main__":
    main()
